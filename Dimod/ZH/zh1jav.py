def reduce_exponent(a: int, k: int, m: int) -> int:
    if m <= 0:
        raise ValueError("Az m-nek pozitív egésznek kell lennie.")
    if gcd(a, m) != 1:
        raise ValueError("Az a és m relatív prím kell hogy legyenek.")

    phi = sum(1 for i in range(1, m + 1) if gcd(i, m) == 1)

    kitevo = k % phi
    return kitevo if kitevo != 0 else phi


