# 1. Írj osztályt, amely megvalósítja az ismétléses kódolást az alábbi váznak megfelelően!
# Amennyiben decode() metódus hibát talál, dobjon ValueError kivételt.
# decode_with_correction() esetén a többségi szavazáshoz használható a collections Python csomagból a Counter osztály most_common() metódusa.
class RepCode:
    def __init__(self, k: int):
        if 1 >= k:
            raise ValueError("k túl kicsi")
        self.k = k

    def encode(self, msg: str) -> str:
        return ''.join(c * self.k for c in msg)

    def decode(self, coded_msg: str) -> str:
        if len(coded_msg) % self.k != 0:
            raise ValueError("rossz hossz")

        decoded = []
        for i in range(0, len(coded_msg), self.k):
            block = coded_msg[i:i + self.k]
            if len(set(block)) != 1:  # Ha a blokkban többféle karakter van, hiba történt
                raise ValueError("hiba a kódszóban")
            decoded.append(block[0])
        return ''.join(decoded)

    def decode_with_correction(self, coded_msg: str) -> str:
        if len(coded_msg) % self.k != 0:
            raise ValueError("rossz hossz")

        decoded = []
        for i in range(0, len(coded_msg), self.k):
            block = coded_msg[i:i + self.k]
            most_common_char, _ = Counter(block).most_common(1)[0]
            decoded.append(most_common_char)
        return ''.join(decoded)

# 2. Írj függvényt, amely két bináris kódszó esetén meghatározza azok Hamming-távolságát!
# Pl. hamming_distance('000', '010') == 1
# Amennyiben két kódszó nem összehasonlítható, a függvény dobjon ValueError kivételt.
def hamming_distance(u: str, v: str) -> int:
    if len(u) != len(v):
        raise ValueError("Nem egyeznek a hosszok")

    distance = 0
    for i in range(len(u)):
        if u[i] != v[i]:
            distance += 1
    return distance

# 3. Írj függvényt, amely egy, a kódszavak halmazával megadott bináris kód Hamming-távolságát határozza meg!
# Amennyiben a kód nem egyenletes, a függvény dobjon ValueError kivételt.
def code_distance(code_words: list[str]) -> int:
    if len(code_words) < 2:
        raise ValueError("A kódnak legalább két kódszót kell tartalmaznia.")
    
    min_distance = float('inf')
    for u,v in itertools.combinations(code_words, 2):
        distance = hamming_distance(u, v)
        if distance < min_distance:
            min_distance = distance

    return min_distance

